export const DICTS: Record<Language, Dict> = { "pt-BR": pt, en, es };

export function translate(lang: Language, key: string, vars?: Record<string, string | number>) {
  const raw = DICTS[lang]?.[key] ?? pt[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (_m, name: string) => String(vars[name] ?? ""));
}

/** Reads the language from settings and returns a translate helper. */
export function useTranslation(lang: Language) {
  const t = useCallback(
    (key: string, vars?: Record<string, string | number>) => translate(lang, key, vars),
    [lang],
  );
  return useMemo(() => ({ t, lang, locale: LOCALES[lang] ?? "pt-BR" }), [t, lang]);
}
